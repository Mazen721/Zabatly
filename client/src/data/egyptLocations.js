export function getGovernorateNames() {
  return EGYPT_GOVERNORATES.map((g) => g.name).sort((a, b) => a.localeCompare(b));
}

export function getCitiesByGovernorate(governorateName) {
  const gov = EGYPT_GOVERNORATES.find((g) => g.name === governorateName);
  return gov ? [...gov.cities].sort((a, b) => a.name.localeCompare(b.name)) : [];
}

export function getAllCities() {
  const cities = [];
  EGYPT_GOVERNORATES.forEach((gov) => {
    gov.cities.forEach((city) => {
      cities.push({ ...city, governorate: gov.name });
    });
  });
  return cities.sort((a, b) => a.name.localeCompare(b.name));
}

export function getCityCoordinates(governorateName, cityName) {
  const cities = getCitiesByGovernorate(governorateName);
  return cities.find((c) => c.name === cityName) || null;
}

export function getVehicleAreaLabel(vehicle) {
  if (vehicle?.governorate && vehicle?.city) {
    return `${vehicle.governorate}, ${vehicle.city}`;
  }
  return vehicle?.address || 'Alexandria';
}

export function getVehicleExactAddress(vehicle) {
  if (vehicle?.governorate && vehicle?.city && vehicle?.address) {
    return vehicle.address;
  }
  return '';
}

export function getFilterCityOptions(vehicles = []) {
  const allNames = new Set(getAllCities().map((c) => c.name));
  vehicles.forEach((v) => {
    if (v.city) allNames.add(v.city);
  });

  const listedSet = new Set();
  vehicles.forEach((v) => {
    if (v.city) listedSet.add(v.city);
  });

  const listed = Array.from(listedSet).sort((a, b) => a.localeCompare(b));
  const others = Array.from(allNames)
    .filter((name) => !listedSet.has(name))
    .sort((a, b) => a.localeCompare(b));

  return {
    listed: listed.map((name) => ({ value: name, label: name })),
    others: others.map((name) => ({ value: name, label: name })),
  };
}
